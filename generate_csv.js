function sup(n) {
    const sups = {'0':'⁰','1':'¹','2':'²','3':'³','4':'⁴','5':'⁵','6':'⁶','7':'⁷','8':'⁸','9':'⁹','-':'⁻'};
    return String(n).split('').map(d => sups[d] || d).join('');
}
function repeatMul(num, count) {
    return Array(Math.max(1, count)).fill(num).join(' × ');
}
function repeatAdd(num, count) {
    return Array(Math.max(1, count)).fill(num).join(' + ');
}

